const num = (name) => ({ name, type: "number" });
const bool = (name) => ({ name, type: "boolean" });
const str = (name, values) => ({ name, type: "string", values });
const pre = (id, field, operator, value) => ({ id, type: "input_constraint", field, operator, value });

function task(spec) {
  const priority = spec.priority ?? "normal";
  return {
    sentence: spec.sentence,
    seeded: spec.seeded,
    contract: {
      id: spec.id,
      name: spec.name,
      priority,
      gate: priority === "critical" ? "block" : "report",
      revision: 1,
      approval: { status: "approved", by: "experimenter" },
      target: { operation: spec.operation, inputs: spec.inputs },
      observables: spec.observables,
      preconditions: spec.preconditions,
      cases: spec.cases,
      properties: spec.properties,
      evidence: {
        minimum: [
          ...spec.cases.map((item) => ({ kind: "example_case", ref: item.id })),
          ...spec.properties.map((item) => ({ kind: "property", ref: item.id })),
        ],
      },
      limitations: ["Does not define persistence, concurrency, or currency."],
    },
  };
}

